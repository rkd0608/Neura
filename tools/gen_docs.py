"""Generate the docs site's reference pages from their sources (design §26.4, §26.5).

    python tools/gen_docs.py           # write site/docs/reference/*.md
    python tools/gen_docs.py --check   # exit 1 if any page is stale

Facts that come from code are generated, never hand-written:

- reason-codes.md  from catalog/reason_codes.yaml
- outbound.md      from catalog/outbound.yaml
- api.md           from api/openapi.yaml
- protocol.md      from proto/neura/v1/*.proto (protoc, with the comments)
- sdk.md           from the generated SDK (packages/neura-sdk)

The pages are CommonMark (.md): the site renders them literally, without MDX.
"""

from __future__ import annotations

import argparse
import ast
import sys
import tempfile
from collections.abc import Callable, Iterable, Sequence
from pathlib import Path
from typing import Any

import yaml
from google.protobuf import descriptor_pb2
from grpc_tools import protoc

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "site" / "docs" / "reference"
EDIT = "Generated by `tools/gen_docs.py` from `{source}`. Edit the source and run `make gen`."


def front_matter(title: str, description: str, position: int, source: str) -> str:
    return (
        "---\n"
        f"title: {title}\n"
        f"description: {description}\n"
        f"sidebar_position: {position}\n"
        "status: Experimental\n"
        "generated: true\n"
        "---\n\n"
        f"<!-- {EDIT.format(source=source)} -->\n\n"
    )


def cell(text: object) -> str:
    """Text safe inside a Markdown table cell."""
    value = " ".join(str(text).split())
    return value.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def table(headers: list[str], rows: Iterable[Sequence[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def prose(text: str) -> str:
    return text.strip().replace("<", "&lt;").replace(">", "&gt;")


# --- reason codes ---------------------------------------------------------------------------------


def reason_codes() -> str:
    catalog = yaml.safe_load((ROOT / "catalog" / "reason_codes.yaml").read_text(encoding="utf-8"))
    out = front_matter(
        "Reason codes",
        "Every reason code the data plane, site agent, control plane and console use.",
        4,
        "catalog/reason_codes.yaml",
    )
    out += (
        "# Reason codes\n\n"
        "Every refusal, rejection and fault in Neura carries one stable code from a single "
        "catalog, the same in the robot runtime, the gateway, the site agent, the management API "
        "and the console. Codes are never reused or renamed. A `fatal` code latches a fault on "
        "the robot: only an explicit local reset clears it.\n\n"
        f"Catalog version {catalog['catalog_version']}, {len(catalog['codes'])} codes.\n\n"
    )
    areas: dict[str, list[dict[str, Any]]] = {}
    for code in catalog["codes"]:
        areas.setdefault(code["area"], []).append(code)
    for area, codes in areas.items():
        out += f"## {area.replace('_', ' ').capitalize()}\n\n"
        out += table(
            ["Code", "Severity", "Retryable", "HTTP", "Meaning"],
            (
                [
                    f"`{c['code']}`",
                    c["severity"],
                    "yes" if c["retryable"] else "no",
                    c.get("http_status", ""),
                    c["message"],
                ]
                for c in codes
            ),
        )
        out += "\n"
    return out


# --- outbound schema ------------------------------------------------------------------------------


def outbound() -> str:
    schema = yaml.safe_load((ROOT / "catalog" / "outbound.yaml").read_text(encoding="utf-8"))
    out = front_matter(
        "What leaves the site",
        "The published allowlist of everything a site agent may send to Neura.",
        5,
        "catalog/outbound.yaml",
    )
    out += (
        "# What leaves the site\n\n"
        "A site agent sends Neura only the fields listed here and drops anything else before it "
        "leaves the server. Every message it sends is also recorded in the site's hash-chained "
        "outbound ledger (`neura-agent outbound --summary`, `--verify`), so a customer can check "
        "what was sent rather than trust this page. Camera images, robot state, actions and "
        "instructions are in no message, by construction of the protocol.\n\n"
        "Telemetry modes (`NEURA_AGENT_TELEMETRY_MODE`): `standard` sends every field below; "
        "`minimal` sends only the fields marked *minimal*: health, versions, identifiers, states "
        "and reason codes, with no free text and no metrics.\n\n"
        f"Schema version {schema['schema_version']}.\n\n"
    )
    for kind, fields in schema["messages"].items():
        out += f"## Message: `{kind}`\n\n"
        out += table(
            ["Field", "Minimal", "Description"],
            (
                [f"`{path}`", "yes" if f["minimal"] else "no", f["description"]]
                for path, f in fields.items()
            ),
        )
        out += "\n"
    out += "## Operation results\n\n"
    out += table(
        ["Key", "Minimal", "Description"],
        (
            [f"`{key}`", "yes" if f["minimal"] else "no", f["description"]]
            for key, f in schema["results"].items()
        ),
    )
    out += "\n## Metrics (standard mode only)\n\n"
    out += table(
        ["Metric", "Unit", "Labels", "Description"],
        (
            [f"`{name}`", m["unit"], ", ".join(m["labels"]) or "none", m["description"]]
            for name, m in schema["metrics"].items()
        ),
    )
    return out


# --- management API -------------------------------------------------------------------------------


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def api() -> str:
    spec = yaml.safe_load((ROOT / "api" / "openapi.yaml").read_text(encoding="utf-8"))
    info = spec["info"]
    parameters = spec["components"].get("parameters", {})
    out = front_matter(
        "Management API",
        "Every operation of the Neura management API.",
        1,
        "api/openapi.yaml",
    )
    out += f"# Management API\n\n{prose(info['summary'])} Version `{info['version']}`.\n\n"
    out += prose(info["description"]) + "\n\n"
    out += (
        "The machine-readable specification is "
        "[`api/openapi.yaml`](https://github.com/rkd0608/neura/blob/main/api/openapi.yaml); the "
        "[Python SDK](./sdk.md) is generated from it.\n\n"
    )
    by_tag: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, item in spec["paths"].items():
        for method, operation in item.items():
            if not isinstance(operation, dict) or method.startswith("x-"):
                continue
            tag = (operation.get("tags") or ["Other"])[0]
            by_tag.setdefault(tag, []).append((method.upper(), path, operation))
    for tag in [t["name"] for t in spec.get("tags", [])] + sorted(by_tag):
        operations = by_tag.pop(tag, None)
        if not operations:
            continue
        out += f"## {tag}\n\n"
        for method, path, operation in operations:
            out += f"### {prose(operation['summary']).rstrip('.')}\n\n"
            out += f"`{method} {path}` · operation `{operation['operationId']}`\n\n"
            if operation.get("description"):
                out += prose(operation["description"]) + "\n\n"
            rows = []
            for parameter in operation.get("parameters", []):
                if "$ref" in parameter:
                    parameter = parameters[_ref_name(parameter["$ref"])]
                rows.append(
                    [
                        f"`{parameter['name']}`",
                        parameter["in"],
                        "yes" if parameter.get("required") else "no",
                        parameter.get("description", ""),
                    ]
                )
            if rows:
                out += table(["Parameter", "In", "Required", "Description"], rows) + "\n"
            body = operation.get("requestBody")
            if body:
                for content_type, content in body.get("content", {}).items():
                    schema = content.get("schema", {})
                    name = _ref_name(schema["$ref"]) if "$ref" in schema else schema.get("type")
                    out += f"Request body: `{content_type}`, `{name}`.\n\n"
            codes = ", ".join(f"`{code}`" for code in operation.get("responses", {}))
            out += f"Responses: {codes}.\n\n"
    return out


# --- protocol -------------------------------------------------------------------------------------


def _descriptors() -> descriptor_pb2.FileDescriptorSet:
    proto_root = ROOT / "proto"
    sources = sorted(
        str(p.relative_to(proto_root)) for p in (proto_root / "neura" / "v1").glob("*.proto")
    )
    include = Path(protoc.__file__).parent / "_proto"
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "set.pb"
        args = [
            "grpc_tools.protoc",
            f"-I{proto_root}",
            f"-I{include}",
            "--include_source_info",
            f"--descriptor_set_out={out}",
            *sources,
        ]
        if protoc.main(args) != 0:
            raise SystemExit("protoc failed")
        files = descriptor_pb2.FileDescriptorSet()
        files.ParseFromString(out.read_bytes())
    return files


_LABELS = {1: "", 2: "", 3: "repeated "}
_TYPES = {
    descriptor_pb2.FieldDescriptorProto.TYPE_DOUBLE: "double",
    descriptor_pb2.FieldDescriptorProto.TYPE_FLOAT: "float",
    descriptor_pb2.FieldDescriptorProto.TYPE_INT64: "int64",
    descriptor_pb2.FieldDescriptorProto.TYPE_UINT64: "uint64",
    descriptor_pb2.FieldDescriptorProto.TYPE_INT32: "int32",
    descriptor_pb2.FieldDescriptorProto.TYPE_FIXED64: "fixed64",
    descriptor_pb2.FieldDescriptorProto.TYPE_FIXED32: "fixed32",
    descriptor_pb2.FieldDescriptorProto.TYPE_BOOL: "bool",
    descriptor_pb2.FieldDescriptorProto.TYPE_STRING: "string",
    descriptor_pb2.FieldDescriptorProto.TYPE_BYTES: "bytes",
    descriptor_pb2.FieldDescriptorProto.TYPE_UINT32: "uint32",
    descriptor_pb2.FieldDescriptorProto.TYPE_SFIXED32: "sfixed32",
    descriptor_pb2.FieldDescriptorProto.TYPE_SFIXED64: "sfixed64",
    descriptor_pb2.FieldDescriptorProto.TYPE_SINT32: "sint32",
    descriptor_pb2.FieldDescriptorProto.TYPE_SINT64: "sint64",
}


def protocol() -> str:
    files = _descriptors()
    out = front_matter(
        "Protocol",
        "The gRPC services and messages between robots, the gateway, workers, agents and Neura.",
        3,
        "proto/neura/v1",
    )
    out += (
        "# Protocol\n\n"
        "Neura's wire protocol, package `neura.v1`: the robot runtime and the site gateway "
        "(`dataplane.proto`), the site agent and the control plane (`site.proto`), the gateway "
        "and its policy workers (`worker.proto`), and shared types (`common.proto`). Sources: "
        "[`proto/neura/v1`](https://github.com/rkd0608/neura/tree/main/proto/neura/v1).\n\n"
    )
    for file in files.file:
        if not file.package.startswith("neura."):
            continue
        comments: dict[tuple[int, ...], str] = {}
        for location in file.source_code_info.location:
            text = (location.leading_comments or location.trailing_comments).strip()
            if text:
                comments[tuple(location.path)] = " ".join(text.split())
        out += f"## `{file.name}`\n\n"
        for s_index, service in enumerate(file.service):
            out += f"### Service `{service.name}`\n\n"
            if doc := comments.get((6, s_index)):
                out += prose(doc) + "\n\n"
            rows = []
            for m_index, method in enumerate(service.method):
                request = ("stream " if method.client_streaming else "") + method.input_type.rsplit(
                    ".", 1
                )[-1]
                response = (
                    "stream " if method.server_streaming else ""
                ) + method.output_type.rsplit(".", 1)[-1]
                rows.append(
                    [
                        f"`{method.name}`",
                        f"`{request}`",
                        f"`{response}`",
                        comments.get((6, s_index, 2, m_index), ""),
                    ]
                )
            out += table(["RPC", "Request", "Response", "Description"], rows) + "\n"
        for e_index, enum in enumerate(file.enum_type):
            out += f"### Enum `{enum.name}`\n\n"
            if doc := comments.get((5, e_index)):
                out += prose(doc) + "\n\n"
            out += (
                table(
                    ["Value", "Number", "Description"],
                    (
                        [f"`{v.name}`", v.number, comments.get((5, e_index, 2, i), "")]
                        for i, v in enumerate(enum.value)
                    ),
                )
                + "\n"
            )
        out += _messages(file.message_type, (4,), comments, "")
    return out


def _messages(
    messages: Iterable[descriptor_pb2.DescriptorProto],
    path: tuple[int, ...],
    comments: dict[tuple[int, ...], str],
    parent: str,
) -> str:
    out = ""
    for index, message in enumerate(messages):
        here = (*path, index)
        name = f"{parent}{message.name}"
        if message.options.map_entry:
            continue
        out += f"### Message `{name}`\n\n"
        if doc := comments.get(here):
            out += prose(doc) + "\n\n"
        if message.field:
            rows = []
            for f_index, field in enumerate(message.field):
                type_name = (
                    field.type_name.rsplit(".", 1)[-1]
                    if field.type_name
                    else _TYPES.get(field.type, "?")
                )
                oneof = (
                    f" (one of `{message.oneof_decl[field.oneof_index].name}`)"
                    if field.HasField("oneof_index") and not field.proto3_optional
                    else ""
                )
                rows.append(
                    [
                        f"`{field.name}`",
                        f"`{_LABELS[field.label]}{type_name}`",
                        field.number,
                        comments.get((*here, 2, f_index), "") + oneof,
                    ]
                )
            out += table(["Field", "Type", "Number", "Description"], rows) + "\n"
        else:
            out += "No fields.\n\n"
        out += _messages(message.nested_type, (*here, 3), comments, f"{name}.")
    return out


# --- SDK ------------------------------------------------------------------------------------------


def _methods(path: Path, class_name: str) -> list[tuple[str, str, str]]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    found: list[tuple[str, str, str]] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == class_name:
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and (
                    not item.name.startswith("_") or item.name == "__init__"
                ):
                    args = ast.unparse(item.args).replace("self, ", "").replace("self", "")
                    returns = ast.unparse(item.returns) if item.returns else "None"
                    doc = ast.get_docstring(item) or ""
                    found.append((item.name, f"({args}) -> {returns}", " ".join(doc.split())))
    return found


def sdk() -> str:
    package = ROOT / "packages" / "neura-sdk" / "src" / "neura_sdk"
    out = front_matter(
        "Python SDK",
        "The Python client for the management API, generated from its specification.",
        2,
        "packages/neura-sdk",
    )
    out += (
        "# Python SDK\n\n"
        "`neura-sdk` is generated from the [management API](./api.md) specification: one method "
        "per operation, returning the API's JSON objects as typed dictionaries. It sends an "
        "`Idempotency-Key` with every POST and keeps it across retries, so a retried POST is "
        "applied at most once. It retries a request whose problem is marked `retryable` (rate "
        "limited, unavailable, an internal error), honoring `Retry-After`, and raises "
        "`NeuraApiError` with the problem details and their stable reason code.\n\n"
        "```python\n"
        "from neura_sdk import Client\n\n"
        'with Client("https://neura.example", token="...") as neura:\n'
        '    for robot in neura.paginate(neura.list_robots, "prj_..."):\n'
        '        print(robot["metadata"]["name"])\n'
        "```\n\n"
        "## Client\n\n"
    )
    out += table(
        ["Method", "Signature", "Description"],
        (
            [f"`{name}`", f"`{signature}`", doc]
            for name, signature, doc in _methods(package / "client.py", "Client")
        ),
    )
    out += "\n## Operations\n\n"
    out += table(
        ["Method", "Signature", "Description"],
        (
            [f"`{name}`", f"`{signature}`", doc]
            for name, signature, doc in sorted(_methods(package / "_operations.py", "Operations"))
        ),
    )
    return out


PAGES: dict[str, Callable[[], str]] = {
    "reason-codes.md": reason_codes,
    "outbound.md": outbound,
    "api.md": api,
    "protocol.md": protocol,
    "sdk.md": sdk,
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a page is stale")
    args = parser.parse_args()
    stale = []
    for name, render in PAGES.items():
        text = render()
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print("stale generated docs (run `make gen`): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
